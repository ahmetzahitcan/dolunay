# Single-precision (Zfinx) FPU self-test.
#
# Each hart checks the element at index mhartid of every list below.  Failures are
# accumulated into the error mask in x1: bit N is set when test N produced a wrong
# result (the bit assignment is documented in random_floats.py).  x1 == 0 means every
# test passed.  The checks use Zicond only, so no branches are taken.
.section .text
.include "instructions.s"

.equ T_FADD,      0
.equ T_FSUB,      1
.equ T_FMUL,      2
.equ T_FDIV,      3
.equ T_FSQRT,     4
.equ T_FMIN,      5
.equ T_FMAX,      6
.equ T_FSGNJ,     7
.equ T_FSGNJN,    8
.equ T_FSGNJX,    9
.equ T_FLT,      10
.equ T_FLE,      11
.equ T_FEQ,      12
.equ T_FCLASS,   13
.equ T_FCVT_W_S, 14
.equ T_FCVT_WU_S,15
.equ T_FCVT_S_W, 16
.equ T_FCVT_S_WU,17
.equ T_FMADD,    18
.equ T_FMSUB,    19
.equ T_FNMSUB,   20
.equ T_FNMADD,   21

# Compare \result against the \list entry of this hart and OR the matching error bit
# into x1.  Clobbers x20-x23; x1 (mask), x2-x5 and x13 (mhartid) are preserved.
.macro CHECKF result, list, bit
    lla       x20, \list
    sh2add    x20, x13, x20
    flw       f21, 0(x20)
    feq.s     x22, \result, f21
    li        x23, (1 << \bit)
    czero.nez x23, x23, x22
    or        x1, x1, x23
.endm

# Compare \result against the \list entry of this hart and OR the matching error bit
# into x1.  Clobbers x20-x23; x1 (mask), x2-x5 and x13 (mhartid) are preserved.
.macro CHECKX result, list, bit
    lla       x20, \list
    sh2add    x20, x13, x20
    lw        x21, 0(x20)
    xor       x22, \result, x21
    li        x23, (1 << \bit)
    czero.eqz x23, x23, x22
    or        x1, x1, x23
.endm

csrr x13, mhartid
li   x1, 0                  # error mask

# Operands for this hart.
lla    x20, list_a
sh2add x20, x13, x20
flw    f2, 0(x20)           # a
lla    x21, list_b
sh2add x21, x13, x21
flw    f3, 0(x21)           # b
lla    x22, list_c
sh2add x22, x13, x22
flw    f5, 0(x22)           # c

fadd.s f4, f2, f3
CHECKF f4, list_add, T_FADD

fsub.s f4, f2, f3
CHECKF f4, list_sub, T_FSUB

fmul.s f4, f2, f3
CHECKF f4, list_mul, T_FMUL

fdiv.s f4, f2, f3
CHECKF f4, list_div, T_FDIV

fsqrt.s f4, f2
CHECKF f4, list_sqrt, T_FSQRT

fmin.s f4, f2, f3
CHECKF f4, list_min, T_FMIN

fmax.s f4, f2, f3
CHECKF f4, list_max, T_FMAX

fsgnj.s f4, f2, f3
CHECKF f4, list_sgnj, T_FSGNJ

fsgnjn.s f4, f2, f3
CHECKF f4, list_sgnjn, T_FSGNJN

fsgnjx.s f4, f2, f3
CHECKF f4, list_sgnjx, T_FSGNJX

flt.s x4, f2, f3
CHECKX x4, list_lt, T_FLT

fle.s x4, f2, f3
CHECKX x4, list_le, T_FLE

feq.s x4, f2, f3
CHECKX x4, list_eq, T_FEQ

fclass.s x4, f2
CHECKX x4, list_fclass, T_FCLASS

fcvt.w.s x4, f2
CHECKX x4, list_cvt_ws, T_FCVT_W_S

fcvt.wu.s x4, f2
CHECKX x4, list_cvt_wus, T_FCVT_WU_S

fmadd.s f4, f2, f3, f5
CHECKF f4, list_fmadd, T_FMADD

fmsub.s f4, f2, f3, f5
CHECKF f4, list_fmsub, T_FMSUB

fnmsub.s f4, f2, f3, f5
CHECKF f4, list_fnmsub, T_FNMSUB

fnmadd.s f4, f2, f3, f5
CHECKF f4, list_fnmadd, T_FNMADD

lla    x20, list_ia
sh2add x20, x13, x20
lw     x5, 0(x20)           # ia
fcvt.s.w f4, x5
CHECKF f4, list_cvt_sw, T_FCVT_S_W

lla    x20, list_iu
sh2add x20, x13, x20
lw     x5, 0(x20)           # iu
fcvt.s.wu f4, x5
CHECKF f4, list_cvt_swu, T_FCVT_S_WU

wdone
j .

